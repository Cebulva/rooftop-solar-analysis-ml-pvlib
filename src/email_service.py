"""
Email Service for Quote Requests
Sends formatted emails to solar dealers with system specifications.
"""

import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import Optional
from dataclasses import dataclass
from datetime import datetime


@dataclass
class QuoteEmailData:
    """Data structure for quote request emails."""
    # Dealer info
    dealer_name: str
    dealer_email: str

    # System specifications
    system_kwp: float
    panel_count: int
    roof_area_sqm: float
    roof_tilt: float
    roof_orientation: str
    estimated_production: float
    installation_address: str
    lat: float
    lon: float

    # Customer info
    customer_name: str
    customer_email: str
    customer_phone: Optional[str] = None
    additional_notes: Optional[str] = None

    # Options
    include_battery: bool = False
    include_financing: bool = False
    include_permits: bool = False

    # Tracking
    inquiry_id: Optional[str] = None


def get_smtp_config() -> dict:
    """Get SMTP configuration from environment variables."""
    return {
        "host": os.getenv("SMTP_HOST", "smtp.gmail.com"),
        "port": int(os.getenv("SMTP_PORT", "587")),
        "user": os.getenv("SMTP_USER", ""),
        "password": os.getenv("SMTP_PASSWORD", ""),
        "from_name": os.getenv("SMTP_FROM_NAME", "SolarSight AI"),
    }


def format_quote_email_text(data: QuoteEmailData) -> str:
    """Format the quote request as plain text."""

    # Build options list
    options = []
    if data.include_battery:
        options.append("Include battery storage options")
    if data.include_financing:
        options.append("Interested in financing")
    if data.include_permits:
        options.append("Need permit assistance")

    options_text = "\n".join(f"  - {opt}" for opt in options) if options else "  None specified"

    text = f"""
Solar Installation Quote Request
================================

A potential customer has requested a quote through SolarSight AI.

SYSTEM SPECIFICATIONS
---------------------
System Size:        {data.system_kwp:.2f} kWp
Panel Count:        {data.panel_count} panels
Roof Area:          {data.roof_area_sqm:.1f} m²
Roof Tilt:          {data.roof_tilt:.0f}°
Roof Orientation:   {data.roof_orientation}
Est. Annual Output: {data.estimated_production:,.0f} kWh/year

INSTALLATION ADDRESS
--------------------
{data.installation_address}
Coordinates: {data.lat:.6f}, {data.lon:.6f}

CUSTOMER CONTACT
----------------
Name:  {data.customer_name}
Email: {data.customer_email}
Phone: {data.customer_phone or 'Not provided'}

ADDITIONAL REQUESTS
-------------------
{options_text}

CUSTOMER NOTES
--------------
{data.additional_notes or 'No additional notes'}

---
This quote request was generated by SolarSight AI
Inquiry ID: {data.inquiry_id or 'N/A'}
Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}

Please respond directly to the customer at: {data.customer_email}
"""
    return text.strip()


