def send_quote_email(data: QuoteEmailData) -> tuple[bool, str]:
    """
    Send a quote request email to the dealer.

    Args:
        data: QuoteEmailData containing all information

    Returns:
        Tuple of (success: bool, message: str)
    """
    config = get_smtp_config()

    if not config["user"] or not config["password"]:
        return False, "Email not configured. Please set SMTP_USER and SMTP_PASSWORD environment variables."

    if not data.dealer_email:
        return False, "Dealer email address not available."

    try:
        # Create message
        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"Quote Request: {data.system_kwp:.1f} kWp Solar System - {data.installation_address.split(',')[0]}"
        msg["From"] = f"{config['from_name']} <{config['user']}>"
        msg["To"] = data.dealer_email
        msg["Reply-To"] = data.customer_email

        # Attach both plain text and HTML versions
        text_part = MIMEText(format_quote_email_text(data), "plain", "utf-8")
        html_part = MIMEText(format_quote_email_html(data), "html", "utf-8")

        msg.attach(text_part)
        msg.attach(html_part)

        # Send email
        with smtplib.SMTP(config["host"], config["port"]) as server:
            server.starttls()
            server.login(config["user"], config["password"])
            server.send_message(msg)

        return True, f"Quote request sent successfully to {data.dealer_name}"

    except smtplib.SMTPAuthenticationError:
        return False, "Email authentication failed. Please check SMTP credentials."
    except smtplib.SMTPException as e:
        return False, f"Failed to send email: {str(e)}"
    except Exception as e:
        return False, f"Unexpected error: {str(e)}"


def send_confirmation_email(
    customer_email: str,
    customer_name: str,
    dealer_name: str,
    system_kwp: float
) -> tuple[bool, str]:
    """
    Send a confirmation email to the customer.

    Args:
        customer_email: Customer's email address
        customer_name: Customer's name
        dealer_name: Name of the dealer contacted
        system_kwp: System size requested

    Returns:
        Tuple of (success: bool, message: str)
    """
    config = get_smtp_config()

    if not config["user"] or not config["password"]:
        return False, "Email not configured"

    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"Quote Request Confirmation - SolarSight AI"
        msg["From"] = f"{config['from_name']} <{config['user']}>"
        msg["To"] = customer_email

        text = f"""
Hello {customer_name},

Your quote request has been sent successfully!

Details:
- Dealer: {dealer_name}
- System Size: {system_kwp:.2f} kWp

The dealer should contact you within 1-2 business days.

Best regards,
SolarSight AI Team
"""

        html = f"""
<!DOCTYPE html>
<html>
<body style="font-family: Arial, sans-serif; line-height: 1.6;">
    <div style="max-width: 500px; margin: 0 auto; padding: 20px;">
        <h2 style="color: #f39c12;">☀️ Quote Request Sent!</h2>
        <p>Hello {customer_name},</p>
        <p>Your quote request has been sent successfully to <strong>{dealer_name}</strong>.</p>
        <div style="background: #f9f9f9; padding: 15px; border-radius: 4px; margin: 15px 0;">
            <p style="margin: 0;"><strong>System Size:</strong> {system_kwp:.2f} kWp</p>
        </div>
        <p>The dealer should contact you within 1-2 business days.</p>
        <p style="color: #666; font-size: 14px;">Best regards,<br>SolarSight AI Team</p>
    </div>
</body>
</html>
"""

        msg.attach(MIMEText(text, "plain", "utf-8"))
        msg.attach(MIMEText(html, "html", "utf-8"))

        with smtplib.SMTP(config["host"], config["port"]) as server:
            server.starttls()
            server.login(config["user"], config["password"])
            server.send_message(msg)

        return True, "Confirmation sent"

    except Exception as e:
        return False, str(e)


